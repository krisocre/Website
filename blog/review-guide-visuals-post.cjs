const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');

function reviewCover(slug) {
  const visual = visuals[slug];
  if (!visual) return undefined;
  return {
    file: slug + '-lead.webp',
    alt: visual.headline + '. ' + [visual.left, visual.right].map(([label, value, detail]) =>
      label + '. ' + (value ? value + '. ' : '') + detail
    ).join(' '),
    caption: visual.caption
  };
}

function reviewLead(slug) {
  const cover = reviewCover(slug);
  if (!cover) return '';
  return `<figure class="review-visual-lead">
    <img src="assets/${cover.file}" width="1200" height="630" decoding="async" alt="${escape(cover.alt)}">
    <figcaption>${escape(cover.caption)}</figcaption>
  </figure>`;
}

function withReviewCheckpoint(slug, body) {
  const checkpoint = visuals[slug]?.checkpoint;
  if (!checkpoint) return body;
  const marker = '<h2 id="' + checkpoint.before + '">';
  if (!body.includes(marker)) throw new Error('Missing review checkpoint section for ' + slug);
  const rows = checkpoint.rows.map(([label, text]) => '<div><dt>' + escape(label) + '</dt><dd>' + escape(text) + '</dd></div>').join('');
  const panel = `<aside class="review-evidence-visual" aria-label="${escape(checkpoint.heading)}">
    <h3>${escape(checkpoint.heading)}</h3>
    <dl>${rows}</dl>
  </aside>`;
  return body.replace(marker, () => panel + '\n' + marker);
}

module.exports = { visuals, reviewCover, reviewLead, withReviewCheckpoint };
